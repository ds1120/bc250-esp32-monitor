"""Embed SD defaults in every firmware build, without credentials."""
from pathlib import Path
import hashlib
import json


def generate(project):
    source=project.parent/'sdcard/bc250'
    out=['#pragma once','// Generated by embed_sd_defaults.py; edit sdcard/bc250 instead.',
         'struct EmbeddedSDFile {const char* name;const char* data;size_t size;};']
    entries=[];manifest={}
    for i,name in enumerate(('index.html','style.css','app.js','settings.example.json')):
        data=(source/name).read_text()
        assert ')SD55"' not in data
        variable='SD_DEFAULT_'+str(i)
        out.append('const char '+variable+'[] PROGMEM=R"SD55('+data+')SD55";')
        entries.append('{"'+name+'",'+variable+',sizeof('+variable+')-1}')
        manifest[name]=hashlib.sha256(data.encode()).hexdigest()
    out.append('const EmbeddedSDFile SD_DEFAULT_FILES[]={'+','.join(entries)+'};')
    html=(source/'index.html').read_text().replace('<link rel="stylesheet" href="/style.css">','<style>'+(source/'style.css').read_text()+'</style>').replace('<script src="/app.js"></script>','<script>'+(source/'app.js').read_text()+'</script>')
    assert ')BC250WEB"' not in html
    (project/'src/web_page.h').write_text('#pragma once\nconst char PAGE[] PROGMEM=R"BC250WEB('+html+')BC250WEB";\n')
    (project/'src/sd_defaults_generated.h').write_text('\n'.join(out)+'\n')
    (project/'sd-defaults-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if 'Import' in globals():
    Import('env')
    generate(Path(env['PROJECT_DIR']))
else:
    generate(Path(__file__).resolve().parent)
